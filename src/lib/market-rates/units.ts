// تبدیل واحدهای بازار — تنها محل مجاز تبدیل ریال ↔ تومان.
//
// قانون بازار ایران: ۱ تومان = ۱۰ ریال.
//   - منبع‌های خام (TGJU، bonbast، Exir USDT) مقدار «ریال» می‌دهند.
//   - ذخیره در DB هم «ریال خام» است (singleRate / rawValue).
//   - نمایش به کاربر «تومان» است → ریال ÷ ۱۰.
//
// فقط همین دو تابع را استفاده کنید؛ هیچ‌جا `* 10` یا `/ 10` هاردکد نکنید.
// (باگ ۲۰۲۶-۰۷ double-division از اعمال دوباره‌ی divisor در چند لایه بود —
//  این ماژول تبدیل را تک‌منبعی می‌کند.)
//
// نکته: فیلد generic «divisor» در assembler/cron یک مقیاس واحد نمایش است
// (rawValue ÷ divisor = value) که برای بازار ایران unit='toman' دقیقاً ۱۰
// (= همین تبدیل ریال→تومان) و برای SARA_* (AFN) / طلای جهانی (USD) برابر ۱
// است. چون ادمین می‌تواند divisor را تغییر دهد، آن مسیر generic باقی می‌ماند.
// ---------------------------------------------------------------------------

/** ۱ تومان = ۱۰ ریال — ثابت بازار ایران. */
export const RIAL_PER_TOMAN = 10;

/** تبدیل ریال خام به تومان (خروجی TGJU/bonbast/Exir → نمایش به کاربر). */
export function rialToToman(rial: number): number {
  return rial / RIAL_PER_TOMAN;
}

/** تبدیل تومان به ریال خام (برای ذخیره در DB یا ساخت irrPerEur و …). */
export function tomanToRial(toman: number): number {
  return toman * RIAL_PER_TOMAN;
}
